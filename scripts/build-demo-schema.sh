#!/usr/bin/env bash
#
# Rebuild supabase/demo/schema.sql - the single file pasted into the demo
# Supabase project's SQL Editor to create everything it needs.
#
# It is every migration in order, followed by the two demo-only tables. Nothing
# here is hand-written: run this again whenever a migration is added, so the
# demo project can be rebuilt from scratch in one paste.
#
#   ./scripts/build-demo-schema.sh
#
set -euo pipefail
cd "$(dirname "$0")/.."

OUT=supabase/demo/schema.sql

{
  echo "-- ============================================================================"
  echo "-- Lanework OS - complete schema for the PUBLIC DEMO database."
  echo "--"
  echo "-- Every migration in supabase/migrations/, in order, plus the two tables that"
  echo "-- exist only in the demo (supabase/demo/demo_tables.sql). Paste the whole file"
  echo "-- into the demo project's Supabase SQL Editor and hit Run, once."
  echo "--"
  echo "-- Do NOT run this against the real database: it would create demo_marker"
  echo "-- there, which is the one thing that tells the demo deployment it is safe to"
  echo "-- wipe what it is connected to."
  echo "--"
  echo "-- Every statement is idempotent, so running it twice is safe."
  echo "--"
  echo "-- Generated by scripts/build-demo-schema.sh - do not hand-edit."
  echo "-- ============================================================================"
  echo

  for f in supabase/migrations/*.sql; do
    echo
    echo "-- ----------------------------------------------------------------------------"
    echo "-- $(basename "$f")"
    echo "-- ----------------------------------------------------------------------------"
    echo
    cat "$f"
    echo
  done

  echo
  echo "-- ----------------------------------------------------------------------------"
  echo "-- demo_tables.sql - DEMO DATABASE ONLY"
  echo "-- ----------------------------------------------------------------------------"
  echo
  cat supabase/demo/demo_tables.sql
} > "$OUT"

echo "Wrote $OUT ($(wc -l < "$OUT" | tr -d ' ') lines)"
